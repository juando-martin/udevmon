"""Shell tab completion.

Each shell's side is a few lines (:data:`SCRIPTS`: bash, zsh, fish) that call
``udevmon _complete``; the logic is here, so it can be tested and cannot drift from
the CLI: it reads the real argparse parser and offers live names (devices, tags,
actions, variables) from the config.

``complete()`` returns ``(mode, candidates)``:

* ``words``    -- offer the candidates;
* ``nospace``  -- the same, without adding a space (``key=``);
* ``files`` / ``dirs`` -- let the shell complete paths.
"""

from __future__ import annotations

import argparse
import os
from pathlib import Path

from . import config as cfgmod
from .events import KNOWN_KEYS, STARTUP, TRIGGER_KINDS, VALID_KINDS, VOLATILE_KEYS

#: How the shell offers the candidates (the first line :func:`complete` returns).
WORDS = "words"
NOSPACE = "nospace"  #: words, without a space after (``key=``)
FILES = "files"  #: file names
DIRS = "dirs"  #: folder names

#: Properties usable in --match (everything a thing can have, minus the engine's "event").
MATCH_KEYS = sorted(KNOWN_KEYS[STARTUP] - {"event"})
RULE_KEYS = sorted(set(MATCH_KEYS) - VOLATILE_KEYS)    #: the same, for a tag rule

#: Positional arguments per command, and what each slot completes ("*" repeats the last).
POSITIONALS = {
    ("trigger",): ["device", "trigger-event"],
    ("devices", "show"): ["device"],
    ("devices", "identify"): ["mountpoint"],
    ("devices", "remove"): ["device"],
    ("devices", "tag"): ["device", "tag*"],
    ("devices", "untag"): ["device", "device-tag*"],
    ("devices", "exclude"): ["device", "rule-tag*"],
    ("devices", "include"): ["device", "device-exclusion*"],
    ("tags", "show"): ["tag"],
    ("tags", "remove"): ["declared-tag"],
    ("tags", "set"): ["declared-tag"],
    ("actions", "remove"): ["action"],
    ("devices", "disable"): ["device*"],
    ("devices", "ignore"): ["device*"],
    ("devices", "enable"): ["device*"],
    ("actions", "disable"): ["action*"],
    ("actions", "enable"): ["action*"],
    ("actions", "set"): ["action"],
    ("devices", "set"): ["device"],
    ("devices", "rename"): ["device", "new"],
    ("tags", "rename"): ["tag", "new"],
    ("actions", "rename"): ["action", "new"],
    ("actions", "add"): ["events"],
    ("explain",): ["event"],
    ("edit",): ["config-file"],
    ("apply",): ["file"],
}

#: Every kind a positional slot above may use (tests check these tables against the CLI).
SLOT_KINDS = {"device", "tag", "declared-tag", "action", "device-tag", "events", "event", "new",
              "rule-tag", "device-exclusion", "trigger-event", "mountpoint",
              "config-file", "file"}

#: Slots that take a new name typed by the user, so there is nothing to complete.
FREE_SLOT_KINDS = {"new"}

#: Commands whose positional arguments are deliberately not completed (a new name).
NO_COMPLETION = {("devices", "add"), ("tags", "add")}

#: Options whose value is completed.
OPTION_VALUE_DESTS = {"config", "dest", "device", "tag", "match", "prop", "on",
                      "add_device", "remove_device", "add_tag", "remove_tag", "exclude_tag",
                      "var", "unset_var", "lock", "from_mountpoint", "file", "duration",
                      "shell", "cwd", "unset_env"}
#: What TAB offers for ``pause --for``, common durations that also show the format.
PAUSE_DURATIONS = ("15m", "30m", "1h", "2h", "1d")

#: Options that take free text, which is not completed.
FREE_TEXT_DESTS = {"name", "timeout", "description", "retries", "retry_delay", "retry_backoff",
                   "order", "env"}

HEADER = "# bash completion for udevmon"   #: marks a file as ours (uninstall checks it)

#: The bash completion script (``completion bash`` prints it).
SCRIPT = HEADER + r'''
# generated by `udevmon completion bash`
_udevmon_complete() {
    local cur=${COMP_WORDS[COMP_CWORD]} out mode
    out=$("${COMP_WORDS[0]}" _complete "$COMP_CWORD" "${COMP_WORDS[@]}" 2>/dev/null) \
        || return 0
    mode=${out%%$'\n'*}
    if [[ $out == *$'\n'* ]]; then out=${out#*$'\n'}; else out=; fi
    local IFS=$'\n'
    case $mode in
        words)   COMPREPLY=($(compgen -W "$out" -- "$cur")) ;;
        nospace) compopt -o nospace 2>/dev/null
                 COMPREPLY=($(compgen -W "$out" -- "$cur")) ;;
        files)   compopt -o filenames 2>/dev/null
                 COMPREPLY=($(compgen -f -- "$cur")) ;;
        dirs)    compopt -o filenames 2>/dev/null
                 COMPREPLY=($(compgen -d -- "$cur")) ;;
    esac
    return 0
}
complete -F _udevmon_complete udevmon
'''

#: The zsh completion script (``completion zsh``): a ``#compdef`` file for ``fpath``,
#: which also works when sourced.
ZSH_SCRIPT = r'''#compdef udevmon
# zsh completion for udevmon
# generated by `udevmon completion zsh`
_udevmon() {
    local -a lines cands
    local mode
    lines=("${(@f)$("${words[1]}" _complete $((CURRENT - 1)) "${words[@]}" 2>/dev/null)}")
    mode=${lines[1]}
    cands=("${(@)lines[2,-1]}")
    case $mode in
        words)   compadd -a cands ;;
        nospace) compadd -S '' -a cands ;;
        files)   _files ;;
        dirs)    _files -/ ;;
    esac
}
if [[ ${zsh_eval_context[-1]} == loadautofunc ]]; then
    _udevmon "$@"
else
    compdef _udevmon udevmon
fi
'''

#: The fish completion script (``completion fish``), for ``~/.config/fish/completions``.
FISH_SCRIPT = r'''# fish completion for udevmon
# generated by `udevmon completion fish`
function __udevmon_complete
    set -l words (commandline -opc)
    set -l cur (commandline -ct)
    set -l out (command $words[1] _complete (count $words) $words "$cur" 2>/dev/null)
    or return
    test (count $out) -gt 0; or return
    switch $out[1]
        case words nospace
            if test (count $out) -gt 1
                printf '%s\n' $out[2..-1]
            end
        case files
            __fish_complete_path "$cur"
        case dirs
            __fish_complete_directories "$cur"
    end
end
complete -c udevmon -f -a '(__udevmon_complete)'
'''

#: Each shell's script.
SCRIPTS = {"bash": SCRIPT, "zsh": ZSH_SCRIPT, "fish": FISH_SCRIPT}
#: The line that marks a file as one ``completion install`` wrote (``uninstall`` checks it).
MARKS = {"bash": HEADER, "zsh": "# zsh completion for udevmon",
         "fish": "# fish completion for udevmon"}


# -- reading the parser ---------------------------------------------------------
def _subparsers(parser):
    return next((a for a in parser._actions if isinstance(a, argparse._SubParsersAction)), None)


def _option(parser, name):
    return next((a for a in parser._actions if name in a.option_strings), None)


def _takes_value(action) -> bool:
    return action.nargs != 0


def _options_of(parser) -> list[str]:
    return sorted(o for a in parser._actions for o in a.option_strings)


class _State:
    """Where the words typed so far have taken us in the command tree."""

    def __init__(self):
        self.node = None
        self.path: list[str] = []
        self.positionals: list[str] = []
        self.pending = None          # an option waiting for its value
        self.config: str | None = None
        self.tail = False            # after "--": a command line, not ours to complete


def _join_equals(words):
    """Undo bash's splitting of ``a=b`` into ``a``, ``=``, ``b`` (``=`` is a word break)."""
    out, i = [], 0
    while i < len(words):
        w = words[i]
        while w != "=" and i + 1 < len(words) and words[i + 1] == "=":
            w += "="
            i += 1
            if i + 1 < len(words):
                w += words[i + 1]
                i += 1
        out.append(w)
        i += 1
    return out


def _analyse(parser, words) -> _State:
    st = _State()
    st.node = parser
    for w in _join_equals(words):
        if st.tail or w == "=":
            continue
        if w == "--":
            st.tail = True
            continue
        if st.pending is not None:
            if st.pending.dest == "config":
                st.config = w
            st.pending = None
            continue
        if w.startswith("-") and w != "-":
            name, eq, value = w.partition("=")
            action = _option(st.node, name)
            if action is not None and _takes_value(action):
                if eq:
                    if action.dest == "config":
                        st.config = value
                else:
                    st.pending = action
            continue
        sub = _subparsers(st.node)
        if sub is not None and not st.positionals and w in sub.choices:
            st.node = sub.choices[w]
            st.path.append(w)
            continue
        st.positionals.append(w)
    return st


# -- live names from the config ---------------------------------------------------
def _config(path: str | None):
    try:
        p = Path(path).expanduser() if path else cfgmod.default_config_path()
        return cfgmod.load(p)
    except Exception:                    # completion must never print errors
        return None


def _names(kind: str, cfg, positionals=()) -> list[str]:
    if cfg is None:
        return []
    if kind == "device":
        return list(cfg.devices)
    if kind == "tag":
        return sorted(cfg.all_tag_names())
    if kind == "declared-tag":
        return sorted(cfg.tags)
    if kind == "lock":
        return sorted({a.lock for a in cfg.actions if a.lock})
    if kind == "rule-tag":               # tags a rule can select (the ones worth opting out of)
        return sorted(t for t, tag in cfg.tags.items() if tag.match)
    if kind == "device-exclusion":       # the rule tags the device typed just before opts out of
        device = cfg.devices.get(positionals[0]) if positionals else None
        return list(device.exclude_tags) if device else []
    if kind == "action":
        return [a.name for a in cfg.actions]
    if kind == "device-tag":             # the explicit tags of the device typed just before
        device = cfg.devices.get(positionals[0]) if positionals else None
        return list(device.tags) if device else []
    return []


def _targets(kind: str, cfg, positionals=()) -> list[str]:
    """The devices or tags an action targets: the named action's, else any action's."""
    if cfg is None:
        return []
    actions = [a for a in cfg.actions if positionals and a.name == positionals[0]] \
        or cfg.actions
    names = [n for a in actions for n in (a.devices if kind == "device" else a.tags)]
    return list(dict.fromkeys(names))


def _variables(cfg, positionals=(), kind: str = "device") -> list[str]:
    """Variable names: the device's (or tag's) own when its name was typed, else every
    device's and tag's."""
    if cfg is None:
        return []
    table = cfg.tags if kind == "tag" else cfg.devices
    if positionals and positionals[0] in table:
        return list(table[positionals[0]].vars)
    return list(dict.fromkeys([*(k for d in cfg.devices.values() for k in d.vars),
                               *(k for t in cfg.tags.values() for k in t.vars)]))


def _events(cur: str) -> list[str]:
    """Event kinds, as a comma-separated list: connected,dis<TAB> -> connected,disconnected."""
    head, sep, last = cur.rpartition(",")
    used = set(head.split(",")) if sep else set()
    prefix = head + "," if sep else ""
    return [prefix + k for k in sorted(VALID_KINDS) if k not in used and k.startswith(last)]


def _startswith(candidates, cur):
    return [c for c in candidates if c.startswith(cur)]


# -- the entry point ----------------------------------------------------------------
def complete(parser, words, cword: int):
    """Candidates for ``words[cword]`` of the command line ``words`` (words[0] = program)."""
    cur = words[cword] if cword < len(words) else ""
    before = words[1:cword]
    if cur == "=" or (before and before[-1] == "="):
        return WORDS, []                 # the value half of key=value: nothing to offer
    st = _analyse(parser, before)
    if st.tail:
        return FILES, []                 # the command being scheduled: ordinary completion
    cfg_path = st.config
    if st.pending is not None:
        return _option_value(st, cur)
    if cur.startswith("-"):
        return WORDS, _startswith(_options_of(st.node), cur)
    sub = _subparsers(st.node)
    if sub is not None:
        if st.positionals:
            return WORDS, []
        return WORDS, _startswith(sorted(sub.choices), cur)
    return _positional(st, cur, _config(cfg_path))


def _dropins(st: _State, cur: str):
    """The drop-ins there are, or the folder for a new one (``--file``, ``edit``)."""
    main = Path(st.config).expanduser() if st.config else cfgmod.default_config_path()
    existing = [cfgmod.file_label(main, f) for f in cfgmod.dropin_files(main)]
    return NOSPACE, _startswith([cfgmod.dropin_dir(main).name + "/", *existing], cur)


def _option_value(st: _State, cur: str):
    """``(mode, candidates)`` for the value of the option just typed (``st.pending``)."""
    dest, path = st.pending.dest, tuple(st.path)
    if dest == "config":
        return FILES, []
    if dest == "dest":
        return (DIRS if path[:1] == ("service",) else FILES), []
    if dest == "from_mountpoint":
        return DIRS, []
    if dest == "file":
        return _dropins(st, cur)
    if dest in ("device", "tag"):
        cfg = _config(st.config)
        return WORDS, _startswith(_names("device" if dest == "device" else "tag", cfg), cur)
    if dest == "lock":                   # the lock names already in use
        cfg = _config(st.config)
        return WORDS, _startswith(_names("lock", cfg), cur)
    if dest == "var":                    # NAME=VALUE: offer the names in use, then free text
        return NOSPACE, _startswith([f"{k}=" for k in _variables(_config(st.config))], cur)
    if dest == "unset_var":
        kind = "tag" if path[:1] == ("tags",) else "device"
        return WORDS, _startswith(_variables(_config(st.config), st.positionals, kind), cur)
    if dest == "exclude_tag":
        return WORDS, _startswith(_names("rule-tag", _config(st.config)), cur)
    if dest in ("add_device", "add_tag"):
        cfg = _config(st.config)
        return WORDS, _startswith(_names(dest[4:], cfg), cur)
    if dest in ("remove_device", "remove_tag"):
        return WORDS, _startswith(_targets(dest[7:], _config(st.config), st.positionals), cur)
    if dest == "on":
        return WORDS, _events(cur)
    if dest == "cwd":
        return DIRS, []
    if dest == "unset_env":                  # the action's own environment variables
        cfg = _config(st.config)
        actions = [a for a in (cfg.actions if cfg else ())
                   if not st.positionals or a.name == st.positionals[0]]
        return WORDS, _startswith(list(dict.fromkeys(k for a in actions for k in a.env)), cur)
    if dest == "shell":
        return WORDS, _startswith(sorted(SCRIPTS), cur)
    if dest == "duration":               # examples that show the format; any other works too
        return WORDS, _startswith(list(PAUSE_DURATIONS), cur)
    if dest in ("match", "prop"):
        keys = RULE_KEYS if path in (("tags", "add"), ("tags", "set")) else MATCH_KEYS
        return NOSPACE, _startswith([k + "=" for k in keys], cur)
    return WORDS, []                     # free text: --name, --timeout, --description


def _positional(st: _State, cur: str, cfg):
    """``(mode, candidates)`` for the next positional argument, by its slot kind in
    :data:`POSITIONALS`."""
    slots = POSITIONALS.get(tuple(st.path))
    if not slots:
        return WORDS, []
    index = len(st.positionals)
    slot = slots[index] if index < len(slots) else (slots[-1] if slots[-1].endswith("*") else None)
    if slot is None:
        return WORDS, []
    kind = slot.rstrip("*")
    if kind == "events":
        return WORDS, _events(cur)
    if kind == "event":
        return WORDS, _startswith(sorted(VALID_KINDS), cur)
    if kind == "trigger-event":
        return WORDS, _startswith(sorted(TRIGGER_KINDS), cur)
    if kind == "mountpoint":
        return DIRS, []
    if kind == "file":
        return FILES, []
    if kind == "config-file":
        return _dropins(st, cur)
    if kind in FREE_SLOT_KINDS:
        return WORDS, []
    return WORDS, _startswith(_names(kind, cfg, st.positionals), cur)


# -- installing -----------------------------------------------------------------------
def default_install_path(shell: str = "bash") -> Path:
    """Where ``shell`` loads the user's completions for ``udevmon`` from: bash-completion's
    user folder, a zsh ``site-functions`` folder (which must be in ``fpath``), or fish's
    ``completions`` folder."""
    data = os.environ.get("XDG_DATA_HOME") or os.path.expanduser("~/.local/share")
    if shell == "zsh":
        return Path(data) / "zsh" / "site-functions" / "_udevmon"
    if shell == "fish":
        conf = os.environ.get("XDG_CONFIG_HOME") or os.path.expanduser("~/.config")
        return Path(conf) / "fish" / "completions" / "udevmon.fish"
    return Path(data) / "bash-completion" / "completions" / "udevmon"


def is_ours(text: str, shell: str) -> bool:
    """Whether ``text`` is a completion script that ``completion install`` wrote."""
    return MARKS[shell] in text.splitlines()[:2]
