"""Derive the package version from git, formatted exactly like setuptools-scm.

Uses setuptools-scm's default schemes, without depending on it:

* ``guess-next-dev``: on a tag the version is the tag (``0.2.0``); after it, the last
  number is bumped and ``.devN`` (N = commits since the tag) is added (``0.2.1.dev5``);
  with no tag at all it is ``0.1.devN`` (N = number of commits).
* ``node-and-date``: anything that is not exactly a clean tag gets a local part
  ``+g<commit>`` (``g`` plus 9 hex digits, as in setuptools-scm 10), plus ``.d<YYYYMMDD>`` (the build date) when tracked files have
  uncommitted changes. Untracked files do not count.

Standard library only: setup.py imports this module before anything is installed.
Without git (or outside a git checkout) the version comes from ``PKG-INFO`` (an sdist),
else ``0.0.0+unknown``; this never raises.
"""

from __future__ import annotations

import os
import re
import subprocess
from datetime import datetime, timezone
from pathlib import Path

FALLBACK = "0.0.0+unknown"
_DESCRIBE = re.compile(r"^(?P<tag>.+)-(?P<distance>\d+)-g(?P<node>[0-9a-f]+)(?P<dirty>-dirty)?$")
NODE_LENGTH = 10                 # "g" + 9 hex digits: what setuptools-scm keeps of the hash
_TAG = re.compile(r"^(?:[\w-]+-)?[vV]?(?P<version>\d+(?:\.\d+)*[^+]*)")


def _git(root: Path, *args: str) -> str | None:
    """Run git in ``root``; stdout, or None if git is missing or the command fails."""
    try:
        done = subprocess.run(["git", "-C", str(root), *args], capture_output=True, text=True,
                              env={**os.environ, "LC_ALL": "C"}, timeout=30)
    except (OSError, subprocess.SubprocessError):
        return None
    return done.stdout.strip() if done.returncode == 0 else None


def _bump(version: str) -> str:
    """Increment the trailing number: 0.1.0 -> 0.1.1, 0.2 -> 0.3, 1.0rc1 -> 1.0rc2."""
    m = re.match(r"^(.*?)(\d+)$", version)
    return f"{m.group(1)}{int(m.group(2)) + 1}" if m else version + ".1"


def _normalize_tag(tag: str) -> str | None:
    m = _TAG.match(tag)
    return m.group("version").lower() if m else None


def git_version(root: Path, now: datetime | None = None) -> str | None:
    """The setuptools-scm style version of the git checkout at ``root``, or None."""
    root = Path(root)
    top = _git(root, "rev-parse", "--show-toplevel")
    if top is None or os.path.realpath(top) != os.path.realpath(root):
        return None                                  # not (the top of) a git checkout
    if _git(root, "rev-parse", "--verify", "--quiet", "HEAD") is None:
        return None                                  # no commits yet
    described = _git(root, "describe", "--dirty", "--tags", "--long", "--abbrev=40",
                     "--match", "*[0-9]*")
    m = _DESCRIBE.match(described) if described else None
    tag = _normalize_tag(m.group("tag")) if m else None
    if m and tag:
        distance, dirty = int(m.group("distance")), bool(m.group("dirty"))
        node = ("g" + m.group("node"))[:NODE_LENGTH]
    else:                                            # no usable tag
        count = _git(root, "rev-list", "HEAD", "--count")
        head = _git(root, "rev-parse", "HEAD")
        if count is None or head is None:
            return None
        tag, distance, node = "0.0", int(count), ("g" + head)[:NODE_LENGTH]
        dirty = bool(_git(root, "status", "--porcelain", "--untracked-files=no"))
    if distance == 0 and not dirty:
        return tag                                   # exactly a clean tag
    date = (now or datetime.now(timezone.utc)).strftime("%Y%m%d")
    return f"{_bump(tag)}.dev{distance}+{node}" + (f".d{date}" if dirty else "")


def _pkg_info_version(root: Path) -> str | None:
    try:
        text = (Path(root) / "PKG-INFO").read_text()
    except OSError:
        return None
    m = re.search(r"^Version:\s*(\S+)", text, re.M)
    return m.group(1) if m else None


def get_version(root: Path) -> str:
    return git_version(root) or _pkg_info_version(root) or FALLBACK


def version_tuple(version: str) -> tuple:
    """(0, 1, 'dev4', 'gabc1234.d20260920'): numbers first, then the other parts."""
    main, _, local = version.partition("+")
    parts = [int(p) if p.isdigit() else p for p in main.split(".")]
    return tuple(parts + ([local] if local else []))


def write_version_file(path: Path, version: str) -> None:
    Path(path).write_text(
        "# file generated by setup.py from git; do not edit\n"
        f"__version__ = version = {version!r}\n"
        f"__version_tuple__ = version_tuple = {version_tuple(version)!r}\n")
